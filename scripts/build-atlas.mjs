// Builds public/tiles/atlas.png from the Kenney "Tiny Town" and "Tiny Dungeon" packs (CC0),
// copying only the tiles the game uses and recoloring the wizard into the Warlock avatar.
// Usage: npm run atlas -- <dir containing town/ and dungeon/ unzipped packs>
import fs from 'node:fs';
import path from 'node:path';
import { PNG } from 'pngjs';

const kenneyDir = process.argv[2];
if (!kenneyDir) {
  console.error('Usage: npm run atlas -- <kenney dir with town/ and dungeon/>');
  process.exit(1);
}

const T = 16;
const COLS = 16;
const sheets = {
  t: PNG.sync.read(fs.readFileSync(path.join(kenneyDir, 'town/Tilemap/tilemap_packed.png'))),
  d: PNG.sync.read(fs.readFileSync(path.join(kenneyDir, 'dungeon/Tilemap/tilemap_packed.png'))),
};

// name -> [sheet, index in a 12-column packed sheet, optional recolor]
const WARLOCK = {
  '9b4ca3': '4b2a6e', // robe
  d176d0: '7ee06a', // hat band -> fel glow
  c0cbdc: '2b2440', // beard -> hood shadow
  aab7cc: '241d36',
  '8b9bb4': '3a2f5a',
  '262b44': '9dff7a', // eyes glow
};
const tiles = {
  grass: ['t', 0], grassTuft: ['t', 1], grassFlower: ['t', 2],
  treeAutumnTop: ['t', 3], treeAutumnBottom: ['t', 15], treeGreenTop: ['t', 4], treeGreenBottom: ['t', 16],
  bush: ['t', 5], sprout: ['t', 17], smallAutumn: ['t', 27], smallGreen: ['t', 28], mushroom: ['t', 29],
  road: ['t', 25], sand: ['t', 40], cobble: ['t', 43], stoneFloor: ['t', 109],
  roofRedL: ['t', 52], roofRedM: ['t', 53], roofRedGable: ['t', 67],
  roofBlueL: ['t', 48], roofBlueM: ['t', 49], roofBlueGable: ['t', 63],
  wall: ['t', 72], door: ['t', 85], window: ['t', 84], sign: ['t', 83], barrel: ['t', 130],
  battlementL: ['t', 99], battlementM: ['t', 100], battlementR: ['t', 101],
  gateTopL: ['t', 111], gateTopM: ['t', 112], gateTopR: ['t', 113],
  gateBottomL: ['t', 123], gateBottomM: ['t', 124], gateBottomR: ['t', 125],
  warlock: ['d', 84, WARLOCK],
  boss1: ['d', 109], boss2: ['d', 121], boss3: ['d', 122], boss4: ['d', 110], boss5: ['d', 92],
  chest: ['d', 89], banner: ['d', 29],
};

const names = Object.keys(tiles);
const rows = Math.ceil(names.length / COLS);
const out = new PNG({ width: COLS * T, height: rows * T });
const hex = (d, i) => [0, 1, 2].map((c) => d[i + c].toString(16).padStart(2, '0')).join('');

names.forEach((name, n) => {
  const [sheetKey, idx, recolor] = tiles[name];
  const src = sheets[sheetKey];
  const sx = (idx % 12) * T;
  const sy = Math.floor(idx / 12) * T;
  for (let y = 0; y < T; y++) {
    for (let x = 0; x < T; x++) {
      const si = ((sy + y) * src.width + sx + x) * 4;
      const di = ((Math.floor(n / COLS) * T + y) * out.width + (n % COLS) * T + x) * 4;
      let rgb = [src.data[si], src.data[si + 1], src.data[si + 2]];
      if (recolor) {
        const h = hex(src.data, si);
        // Skin pixels on the lower rows are the hands: they hold fel fire.
        const mapped = h === 'f7c282' && y >= 10 ? '8cff6a' : recolor[h];
        if (mapped) rgb = [0, 2, 4].map((o) => parseInt(mapped.slice(o, o + 2), 16));
      }
      out.data[di] = rgb[0];
      out.data[di + 1] = rgb[1];
      out.data[di + 2] = rgb[2];
      out.data[di + 3] = src.data[si + 3];
    }
  }
});

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')), '..');
fs.mkdirSync(path.join(root, 'public/tiles'), { recursive: true });
fs.writeFileSync(path.join(root, 'public/tiles/atlas.png'), PNG.sync.write(out));
const index = Object.fromEntries(names.map((name, n) => [name, n]));
fs.writeFileSync(
  path.join(root, 'src/ui/map/atlas-index.ts'),
  `// Generated by scripts/build-atlas.mjs — do not edit.\nexport const ATLAS_COLUMNS = ${COLS};\nexport const TILE = ${T};\nexport const TILES = ${JSON.stringify(index, null, 2)} as const;\nexport type TileName = keyof typeof TILES;\n`,
);
console.log(`atlas: ${names.length} tiles, ${out.width}x${out.height}`);
